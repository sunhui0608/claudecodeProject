"""Generate bilingual (Chinese/English) investigation report from analysis outputs."""
import json
from datetime import datetime
from pathlib import Path

import pandas as pd

BASE_DIR = Path.home() / "qingjian" / "寺庙核查"
ANALYSIS_DIR = BASE_DIR / "analysis"
REPORT_PATH = BASE_DIR / "核查报告.md"

ACCOUNTS = [
    "lammichaeltw", "penpen_popnews", "FreeAll_protest", "shKdufS8Ln39062",
    "zetu_rrr", "tourouken555", "ChinaVideos1", "manchuriareview",
    "sam51824016070", "QuanLujun", "TruthMedia123", "zhihui999",
    "LucyZha94759559", "xinwendiaocha", "DXDWX999",
]


def load_json(path: Path) -> dict | list | None:
    if not path.exists():
        return None
    return json.loads(path.read_text())


def load_csv(path: Path) -> pd.DataFrame | None:
    if not path.exists():
        return None
    return pd.read_csv(path, index_col=0)


def generate():
    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

    similarity_df = load_csv(ANALYSIS_DIR / "tfidf_similarity_matrix.csv")
    coordination = load_json(ANALYSIS_DIR / "coordination_events.json") or []
    common_followers = load_json(ANALYSIS_DIR / "common_followers.json") or []

    lammi_score = "N/A"
    top_similar_pairs = ""
    sim_table = ""
    if similarity_df is not None:
        if "lammichaeltw" in similarity_df.index and "penpen_popnews" in similarity_df.columns:
            lammi_score = f"{similarity_df.loc['lammichaeltw', 'penpen_popnews']:.4f}"

        # Top 5 most similar pairs (excluding self)
        pairs = []
        idx = list(similarity_df.index)
        for i in range(len(idx)):
            for j in range(i + 1, len(idx)):
                pairs.append((idx[i], idx[j], similarity_df.iloc[i, j]))
        pairs.sort(key=lambda x: x[2], reverse=True)
        top_lines = [f"| @{a} | @{b} | {s:.4f} |" for a, b, s in pairs[:5]]
        top_similar_pairs = "\n".join(top_lines)

        sim_table = similarity_df.round(3).to_markdown()

    coord_count = len(coordination)
    coord_sample = ""
    for e in coordination[:5]:
        accs = ", ".join(f"@{a}" for a in e["accounts"])
        coord_sample += (
            f"- **#{e['hashtag']}** — {accs} "
            f"({e['tweet_count']} posts within 48h, starting {e['window_start'][:10]})\n"
        )

    cf_count = len(common_followers)
    cf_sample = ""
    for cf in common_followers[:10]:
        cf_sample += (
            f"| @{cf.get('screen_name', '?')} "
            f"| {cf['target_count']} "
            f"| {cf.get('account_created_at', 'N/A')[:10]} "
            f"| {', '.join(f'@{a}' for a in cf['follows_targets'][:3])}... |\n"
        )

    accounts_list = "\n".join(f"- @{a}" for a in ACCOUNTS)

    report = f"""# 寺庙视频传播网络核查报告
# Temple Video Network Investigation Report

**生成时间 / Generated:** {now}

---

## 一、核查背景 / Background

本报告对以下 {len(ACCOUNTS)} 个 X (Twitter) 账户的内容及互动网络进行系统性分析，
聚焦于寺庙视频相关内容的传播路径和协调行为。

This report systematically analyzes {len(ACCOUNTS)} X (Twitter) accounts,
focusing on propagation patterns and coordinated behavior related to temple video content.

### 目标账户 / Target Accounts

{accounts_list}

---

## 二、内容相似度分析 / Content Similarity Analysis

使用 TF-IDF 字符 n-gram (1–3) + 余弦相似度对各账号原创推文进行对比。

Character-level TF-IDF (1–3 grams) with cosine similarity applied to original tweets only.

### 焦点对比 / Focal Comparison

| 账户对 / Account Pair | TF-IDF 余弦相似度 / Cosine Similarity |
|---|---|
| @lammichaeltw vs @penpen_popnews | **{lammi_score}** |

> 相似度接近 1.0 表示内容高度一致；接近 0 表示无重叠。
> Score near 1.0 = near-identical content; near 0 = no overlap.

### 最高相似度账户对 / Top Similar Pairs

| 账户 A | 账户 B | 相似度 |
|---|---|---|
{top_similar_pairs}

### 完整相似度矩阵 / Full Similarity Matrix

{sim_table if sim_table else "_（数据不足，矩阵未生成）/ (Insufficient data)_"}

---

## 三、协调发帖检测 / Coordinated Posting Detection

检测窗口：48小时内，≥2 个目标账户使用相同话题标签发帖。
Detection window: same hashtag used by ≥2 target accounts within 48 hours.

**发现协调事件 / Coordination events found: {coord_count}**

{coord_sample if coord_sample else "_未检测到协调事件。/ No coordination events detected._"}

---

## 四、共同粉丝异常分析 / Common Follower Analysis

筛选条件：同时关注 ≥5 个目标账户的粉丝账号。
Filter: accounts following ≥5 target accounts simultaneously.

**可疑共同粉丝总数 / Suspicious common followers: {cf_count}**

{"| 账户 / Account | 关注目标数 / Target Count | 注册时间 / Created | 关注的目标 (前3) / Targets (top 3) |" if cf_sample else ""}
{"| --- | --- | --- | --- |" if cf_sample else ""}
{cf_sample if cf_sample else "_未发现可疑共同粉丝。/ No suspicious common followers found._"}

---

## 五、结论 / Conclusions

1. **内容相似度** (`@lammichaeltw` vs `@penpen_popnews`): {lammi_score}
2. **协调行为**: 检测到 {coord_count} 个48小时窗口内的协调发帖事件
3. **网络连接**: {cf_count} 个账户同时关注 ≥5 个目标账户

---

*报告由自动化脚本生成 / Auto-generated by investigation scripts*
*数据目录 / Data directory: ~/qingjian/寺庙核查/*
"""

    REPORT_PATH.write_text(report, encoding="utf-8")
    print(f"Report written to: {REPORT_PATH}")


if __name__ == "__main__":
    generate()
